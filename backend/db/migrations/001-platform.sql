CREATE TABLE IF NOT EXISTS users (
 id TEXT PRIMARY KEY, google_sub TEXT UNIQUE NOT NULL, email TEXT UNIQUE NOT NULL,
 name TEXT NOT NULL, created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS workspaces (
 id TEXT PRIMARY KEY, name TEXT NOT NULL, created_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS memberships (
 workspace_id TEXT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
 user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 role TEXT NOT NULL CHECK(role IN ('owner','admin','member','viewer')), joined_at BIGINT NOT NULL,
 PRIMARY KEY(workspace_id,user_id)
);
CREATE INDEX IF NOT EXISTS membership_user ON memberships(user_id);
CREATE UNIQUE INDEX IF NOT EXISTS workspace_owner ON memberships(workspace_id) WHERE role = 'owner';
CREATE TABLE IF NOT EXISTS sessions (
 digest TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 csrf TEXT NOT NULL, expires_at BIGINT NOT NULL, created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS session_expiry ON sessions(expires_at);
CREATE TABLE IF NOT EXISTS oauth_states (
 digest TEXT PRIMARY KEY, verifier TEXT NOT NULL, return_to TEXT NOT NULL, expires_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS teams (
 id TEXT PRIMARY KEY, workspace_id TEXT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
 name TEXT NOT NULL, description TEXT NOT NULL DEFAULT '', created_at BIGINT NOT NULL,
 UNIQUE(workspace_id,id), UNIQUE(workspace_id,name)
);
CREATE TABLE IF NOT EXISTS team_members (
 workspace_id TEXT NOT NULL, team_id TEXT NOT NULL, user_id TEXT NOT NULL,
 PRIMARY KEY(team_id,user_id),
 FOREIGN KEY(workspace_id,team_id) REFERENCES teams(workspace_id,id) ON DELETE CASCADE,
 FOREIGN KEY(workspace_id,user_id) REFERENCES memberships(workspace_id,user_id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS invitations (
 id TEXT PRIMARY KEY, workspace_id TEXT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
 digest TEXT UNIQUE NOT NULL, email TEXT NOT NULL, role TEXT NOT NULL CHECK(role IN ('admin','member','viewer')),
 team_id TEXT, invited_by TEXT NOT NULL REFERENCES users(id), expires_at BIGINT NOT NULL,
 accepted_at BIGINT, revoked_at BIGINT, created_at BIGINT NOT NULL,
 FOREIGN KEY(workspace_id,team_id) REFERENCES teams(workspace_id,id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS invitations_workspace ON invitations(workspace_id,created_at DESC);
CREATE TABLE IF NOT EXISTS projects (
 id TEXT PRIMARY KEY, workspace_id TEXT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
 name TEXT NOT NULL, description TEXT NOT NULL DEFAULT '', url TEXT NOT NULL DEFAULT '',
 created_at BIGINT NOT NULL, UNIQUE(workspace_id,id), UNIQUE(workspace_id,name)
);
CREATE TABLE IF NOT EXISTS workspace_reports (
 id TEXT NOT NULL, workspace_id TEXT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
 project_id TEXT, author_id TEXT REFERENCES users(id), assignee_id TEXT,
 document JSONB NOT NULL, version INTEGER NOT NULL DEFAULT 1,
 created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL, PRIMARY KEY(workspace_id,id),
 FOREIGN KEY(workspace_id,project_id) REFERENCES projects(workspace_id,id),
 FOREIGN KEY(workspace_id,assignee_id) REFERENCES memberships(workspace_id,user_id)
);
CREATE INDEX IF NOT EXISTS workspace_reports_created ON workspace_reports(workspace_id,created_at DESC);
CREATE INDEX IF NOT EXISTS workspace_reports_assignee ON workspace_reports(workspace_id,assignee_id);
CREATE TABLE IF NOT EXISTS workspace_artifacts (
 workspace_id TEXT NOT NULL, report_id TEXT NOT NULL, kind TEXT NOT NULL CHECK(kind IN ('screenshot','video')),
 type TEXT NOT NULL, data BYTEA NOT NULL, PRIMARY KEY(workspace_id,report_id,kind),
 FOREIGN KEY(workspace_id,report_id) REFERENCES workspace_reports(workspace_id,id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS report_comments (
 id TEXT PRIMARY KEY, workspace_id TEXT NOT NULL, report_id TEXT NOT NULL, user_id TEXT REFERENCES users(id),
 body TEXT NOT NULL, created_at BIGINT NOT NULL,
 FOREIGN KEY(workspace_id,report_id) REFERENCES workspace_reports(workspace_id,id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS report_comments_report ON report_comments(workspace_id,report_id,created_at);
CREATE TABLE IF NOT EXISTS workspace_activity (
 sequence INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, workspace_id TEXT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
 user_id TEXT REFERENCES users(id), action TEXT NOT NULL, detail TEXT NOT NULL, report_id TEXT, created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS workspace_activity_recent ON workspace_activity(workspace_id,sequence DESC);
CREATE TABLE IF NOT EXISTS notifications (
 id TEXT PRIMARY KEY, workspace_id TEXT NOT NULL, user_id TEXT NOT NULL, title TEXT NOT NULL,
 report_id TEXT, read_at BIGINT, created_at BIGINT NOT NULL,
 FOREIGN KEY(workspace_id,user_id) REFERENCES memberships(workspace_id,user_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS user_notifications ON notifications(user_id,created_at DESC);
CREATE TABLE IF NOT EXISTS subscriptions (
 workspace_id TEXT PRIMARY KEY REFERENCES workspaces(id) ON DELETE CASCADE,
 plan TEXT NOT NULL DEFAULT 'free' CHECK(plan IN ('free','pro','business')),
 status TEXT NOT NULL DEFAULT 'free', customer_id TEXT UNIQUE, subscription_id TEXT UNIQUE,
 product_id TEXT, next_billing_at TEXT, event_at BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS billing_attempts (
 id TEXT PRIMARY KEY, workspace_id TEXT NOT NULL REFERENCES workspaces(id), plan TEXT NOT NULL,
 product_id TEXT NOT NULL, customer_id TEXT, checkout_id TEXT, created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS billing_attempt_workspace ON billing_attempts(workspace_id,created_at DESC);
CREATE TABLE IF NOT EXISTS billing_events (
 id TEXT PRIMARY KEY, type TEXT NOT NULL, event_at BIGINT NOT NULL, processed_at BIGINT NOT NULL
);