CREATE TABLE IF NOT EXISTS reports (
  id TEXT PRIMARY KEY, created_at BIGINT NOT NULL, document TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS reports_created ON reports(created_at DESC, id DESC);
CREATE TABLE IF NOT EXISTS shares (
  digest TEXT PRIMARY KEY, report_id TEXT NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
  expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS shares_report ON shares(report_id);
CREATE TABLE IF NOT EXISTS audit (
  at BIGINT NOT NULL, principal TEXT NOT NULL, action TEXT NOT NULL, report_id TEXT
);
CREATE TABLE IF NOT EXISTS discussion (
  sequence INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id TEXT UNIQUE NOT NULL,
  report_id TEXT NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
  at BIGINT NOT NULL, actor TEXT NOT NULL, kind TEXT NOT NULL, body TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS discussion_report ON discussion(report_id, sequence DESC);
CREATE TABLE IF NOT EXISTS contributors (
  digest TEXT PRIMARY KEY, report_id TEXT NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
  expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS contributors_report ON contributors(report_id);
CREATE TABLE IF NOT EXISTS report_artifacts (
  report_id TEXT NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('screenshot', 'video')),
  type TEXT NOT NULL, data BYTEA NOT NULL,
  PRIMARY KEY (report_id, kind)
);
CREATE TABLE IF NOT EXISTS submission_receipts (
  report_id TEXT PRIMARY KEY REFERENCES reports(id) ON DELETE CASCADE,
  digest TEXT NOT NULL
);